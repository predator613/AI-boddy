-- Демо-прогресс: отметки о выполнении ставились при создании базы, поэтому почти все выглядели
-- просроченными. Переносим их на день срока, чтобы метрика «в срок» была правдоподобной.
UPDATE intern_task_progress pr
SET updated_at = LEAST(pr.updated_at, ((p.start_date + t.due_day - 1) + time '12:00') AT TIME ZONE 'Europe/Moscow')
FROM onboarding_tasks t, intern_profiles p
WHERE pr.status = 'done' AND t.id = pr.task_id AND p.user_id = pr.intern_id AND t.due_day IS NOT NULL;
