-- ---------- Автоматизации ----------
CREATE TABLE mentor_automations (
    mentor_id UUID NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    kind      TEXT NOT NULL CHECK (kind IN ('deadline_reminder', 'weekly_goal_checkin', 'overdue_alert', 'approver_reminder')),
    enabled   BOOLEAN NOT NULL,
    PRIMARY KEY (mentor_id, kind)
);
