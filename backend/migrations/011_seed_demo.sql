-- ===================== События за 3 недели (для метрик и дашборда) =====================
SELECT setseed(0.42);
-- Для каждого рабочего дня и стажера: n вопросов помощнику; на каждый вопрос – ответ,
-- примерно 70% со ссылкой на справочник, примерно 12% переданы наставнику.
CREATE TEMP TABLE demo_days AS
SELECT d::date AS day, p.user_id, 1 + floor(random() * 4)::int AS n
FROM generate_series(current_date - 20, current_date - 1, interval '1 day') AS d
JOIN intern_profiles p ON d >= p.start_date
WHERE extract(isodow FROM d) < 6;

CREATE TEMP TABLE demo_questions AS
SELECT dd.user_id,
       dd.day + make_interval(hours => 10 + floor(random() * 8)::int, mins => floor(random() * 60)::int) AS at,
       random() AS r_source, random() AS r_handoff, random() AS r_article
FROM demo_days dd, generate_series(1, dd.n) AS g;

INSERT INTO events (occurred_at, user_id, event_type)
SELECT day + time '09:30', user_id, 'login' FROM demo_days
UNION ALL SELECT at, user_id, 'chat_message_sent' FROM demo_questions
UNION ALL SELECT at + interval '3 seconds', user_id, 'chat_answer_shown' FROM demo_questions
UNION ALL SELECT at + interval '3 seconds', user_id, 'answer_from_kb' FROM demo_questions WHERE r_source < 0.7
UNION ALL SELECT at + interval '4 seconds', user_id, 'handoff_created' FROM demo_questions WHERE r_handoff < 0.12
UNION ALL SELECT at + interval '1 minute', user_id, 'kb_article_opened' FROM demo_questions WHERE r_article < 0.4;

