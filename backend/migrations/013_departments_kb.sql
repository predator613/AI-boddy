-- ===================== Отделы и каталог =====================

CREATE TABLE departments (
    code      TEXT PRIMARY KEY,
    title     TEXT NOT NULL,                       -- «Отдел оборудования»
    sla_hours INT  NOT NULL CHECK (sla_hours BETWEEN 1 AND 240),
    hours     TEXT NOT NULL DEFAULT '',            -- когда и где работают
    about     TEXT NOT NULL DEFAULT '',            -- с чем приходить
    position  INT  NOT NULL
);

-- Что можно заказать в отдел через AI-buddy.
CREATE TABLE catalog_items (
    code            TEXT PRIMARY KEY,
    department_code TEXT NOT NULL REFERENCES departments (code),
    title           TEXT NOT NULL,                 -- «Ноутбук»
    request_title   TEXT NOT NULL,                 -- «Выдача ноутбука»
    hint            TEXT NOT NULL DEFAULT ''       -- что написать в комментарии
);

CREATE TABLE catalog_aliases (
    alias     TEXT PRIMARY KEY CHECK (alias = lower(alias) AND length(alias) BETWEEN 2 AND 40),
    item_code TEXT NOT NULL REFERENCES catalog_items (code) ON DELETE CASCADE
);

-- Детали заявки в отдел (тип other).
CREATE TABLE service_request_details (
    request_id UUID PRIMARY KEY REFERENCES requests (id) ON DELETE CASCADE,
    item_code  TEXT NOT NULL REFERENCES catalog_items (code),
    comment    TEXT NOT NULL DEFAULT '' CHECK (length(comment) <= 500)
);

UPDATE request_types SET title = 'заявка в отдел' WHERE code = 'other';

